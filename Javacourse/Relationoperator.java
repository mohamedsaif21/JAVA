package Javacourse;

public class Relationoperator {

    public static void main(String[] args) {
        
        int x =5;
        int y =5;

        boolean result = x < y;
        boolean result1 = x > y;
        boolean result2 = x != y;
        boolean result3 = x == y;

        System.out.println(result);
        System.out.println(result1);
        System.out.println(result2);
        System.out.println(result3);
    }
    
}
